#!/usr/bin/env python3
"""Regenerate the complete published household result tables from measured JSON."""
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RUN = ROOT / 'results/household-2026-10-30'
LABELS = {'raw': 'Raw copy', 'apple_lz4': 'Apple LZ4', 'apple_lz4_raw': 'Apple LZ4_RAW',
          'apple_lzfse': 'Apple LZFSE', 'custom_rc': 'Custom V2'}
REFS = ('apple_lz4', 'apple_lz4_raw', 'apple_lzfse')


def main():
    data = json.loads((RUN / 'all-results.json').read_text())
    text = [
        '# Full household corpus results', '',
        'Generated by `python3 scripts/summarize.py` from the committed measurement JSON.', '',
        'One UCI source corpus, four representations/partitions. All 20 method cases passed exact byte round-trip verification. '
        'Each input uses 16 KiB pages, one warmup per method and nine timed trials with shuffled method order. '
        'Times are median milliseconds for the complete input. Brackets show the observed minimum and maximum, not confidence intervals.', '',
        'Host: Apple M4 Pro, 24 GiB RAM, macOS 15.1.1, Apple clang 16, `-O3`. '
        'This single desktop run is not evidence of lower operating-system RSS or faster applications. '
        'The source and compressed representation coexist during the benchmark. '
        'Existing swap use was present; global VM snapshots are context, not a measurement of this process\'s memory savings.', '',
        '[Methodology](METHODOLOGY.md) · [Corpus specification](DATASETS.md) · '
        '[Raw CSV](../results/household-2026-10-30/all-results.csv) · '
        '[All timing samples](../results/household-2026-10-30/all-results.json) · '
        '[Frozen source hashes and system context](../results/household-2026-10-30/frozen-config.json)', '',
    ]
    comparisons = []
    all_wins = 0
    for case in data['corpus']:
        item = case['dataset']
        rows = {r['method']: r for r in case['results']}
        text += ['## ' + item['name'], '',
                 f"{item['size']:,} original bytes ({item['size']/2**20:.2f} MiB); {item['representation']}.", '',
                 '| Method | Stored bytes | Stored / original | Encode ms [min, max] | Decode ms [min, max] |',
                 '|---|---:|---:|---:|---:|']
        for method, label in LABELS.items():
            r = rows[method]
            if not r['verified'] or len(r['encode_samples_ms']) != 9 or len(r['decode_samples_ms']) != 9:
                raise RuntimeError('Incomplete verified trial series')
            timing = []
            for key in ('encode', 'decode'):
                values = r[key + '_samples_ms']
                timing.append(f"{r[key+'_ms']:.3f} [{min(values):.3f}, {max(values):.3f}]")
            text.append(f"| {label} | {r['total_storage_bytes']:,} | {r['total_storage_bytes']/item['size']*100:.3f}% | "
                        + ' | '.join(timing) + ' |')
        text += ['', '| Reference | Size criterion | Encoding criterion | Decoding criterion | Strict win | Paired rounds meeting all criteria |',
                 '|---|---|---|---|---|---:|']
        custom = rows['custom_rc']
        wins = []
        for ref in REFS:
            baseline = rows[ref]
            size_ok = custom['total_storage_bytes'] <= baseline['total_storage_bytes']
            enc_ok = custom['encode_ms'] <= .90 * baseline['encode_ms']
            dec_ok = custom['decode_ms'] <= .90 * baseline['decode_ms']
            win = size_ok and enc_ok and dec_ok
            paired = sum(size_ok and e <= .9*b and d <= .9*c for e, b, d, c in zip(
                custom['encode_samples_ms'], baseline['encode_samples_ms'],
                custom['decode_samples_ms'], baseline['decode_samples_ms']))
            text.append('| ' + LABELS[ref] + ' | ' + ' | '.join('Pass' if x else 'Fail' for x in
                        (size_ok, enc_ok, dec_ok, win)) + f' | {paired}/9 |')
            comparisons.append({'input': item['name'], 'reference': ref,
                'custom_storage_over_reference': custom['total_storage_bytes']/baseline['total_storage_bytes'],
                'encode_speedup_reference_over_custom': baseline['encode_ms']/custom['encode_ms'],
                'decode_speedup_reference_over_custom': baseline['decode_ms']/custom['decode_ms'],
                'size_pass': size_ok, 'encode_pass': enc_ok, 'decode_pass': dec_ok,
                'strict_win': win, 'paired_rounds_passed': paired})
            wins.append(win)
        all_wins += all(wins)
        text += ['']
    text += ['## Interpretation', '',
        'The fixed criterion is: stored bytes no larger than the reference, median encoding time at most '
        '90% of the reference, and median decoding time at most 90% of the reference. '
        'Paired-round counts are descriptive checks on the nine collected rounds; they are not a significance test.', '',
        f'**{all_wins}/{len(data["corpus"])} inputs satisfy this criterion against all three Apple references.** '
        'The column-major numeric input satisfies it against both LZ4 variants, while LZFSE retains a size advantage. '
        'The row-major layout trades greater size for lower codec time. The original text largely falls back to raw bytes, '
        'so its fast custom timing is not a compression victory.', '',
        'The same frozen V2 codec was used for every input. No codec adjustment followed these new measurements. '
        'The four inputs remain representations/partitions of one dataset, and the earlier synthetic wins are not independent validation of this real corpus.', '',
    ]
    (ROOT / 'docs/HOUSEHOLD_RESULTS.md').write_text('\n'.join(text))
    with (RUN / 'comparisons.csv').open('w', newline='') as stream:
        writer = csv.DictWriter(stream, fieldnames=list(comparisons[0]))
        writer.writeheader()
        writer.writerows(comparisons)
    print(f'Published tables: {len(data["corpus"])} inputs, {len(comparisons)} reference comparisons.')


if __name__ == '__main__':
    main()
